  private detectParallelLcdMode(
    node: Node,
  ): "4bit" | "8bit" {
    const configured =
      node.data?.lcdMode;

    if (
      typeof configured === "string" &&
      configured.toLowerCase() === "8bit"
    ) {
      return "8bit";
    }

    const graph =
      createCircuitGraph(
        this.circuitNodes,
        this.circuitEdges,
      );

    const wiredPins = new Set<string>();

    for (const wire of graph.wires) {
      for (const ref of [wire.source, wire.target]) {
        if (ref.nodeId === node.id) {
          wiredPins.add(
            ref.pinId.toUpperCase(),
          );
        }
      }
    }

    return ["D0", "D1", "D2", "D3"].some(
      (pin) => wiredPins.has(pin),
    )
      ? "8bit"
      : "4bit";
  }

  private isLcdPowered(
    component: {
      terminals: Record<string, string | null>;
    },
  ): boolean {
    const vcc =
      component.terminals.VDD ??
      component.terminals.VCC ??
      null;

    const gnd =
      component.terminals.VSS ??
      component.terminals.GND ??
      null;

    return Boolean(
      vcc &&
      gnd &&
      (
        this.powerState.sourceNets.has(vcc) ||
        this.powerState.netVoltages[vcc] === 5 ||
        this.powerState.netVoltages[vcc] === 3.3
      ) &&
      this.powerState.groundNets.has(gnd),
    );
  }

  private isLcdI2cConnected(
    componentId: string,
  ): boolean {
    if (!this.netlist) {
      return false;
    }

    const component =
      this.netlist.components.find(
        (item) => item.id === componentId,
      );

    if (!component) {
      return false;
    }

    const netHasArduinoPin = (
      netId: string | null | undefined,
      pinName: string,
    ): boolean => {
      if (!netId) {
        return false;
      }

      return (
        this.netlist!.netToPins
          .get(netId)
          ?.some(
            (pin) =>
              pin.pinId.toUpperCase() ===
              pinName.toUpperCase(),
          ) ?? false
      );
    };

    /*
     * Arduino UNO hardware TWI is on A4/SDA and A5/SCL.
     * Require the actual circuit topology to connect both lines.
     * VCC/GND must also exist on the LCD component.
     */
    return (
      netHasArduinoPin(
        component.terminals.SDA,
        "A4",
      ) &&
      netHasArduinoPin(
        component.terminals.SCL,
        "A5",
      ) &&
      this.isLcdPowered(component)
    );
  }

  private getConnectedArduinoGpioPin(
    componentId: string,
    terminal: string,
  ): string | null {
    if (!this.netlist) return null;

    const component = this.netlist.components.find(
      (item) => item.id === componentId,
    );
    const netId = component?.terminals[terminal];

    if (!netId) return null;

    const refs = this.netlist.netToPins.get(netId) ?? [];

    for (const ref of refs) {
      if (!/^(?:D|A)\d+$/i.test(ref.pinId)) continue;

      const node = this.circuitNodes.find(
        (candidate) => candidate.id === ref.nodeId,
      );

      const type = String(
        node?.data?.componentType ??
          node?.type ??
          "",
      ).toLowerCase();

      if (
        type === "arduino-uno" ||
        type === "arduino"
      ) {
        return ref.pinId.toUpperCase();
      }
    }

    return null;
  }


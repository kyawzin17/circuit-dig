  private isServoPowered(
    component: Netlist["components"][number],
  ): boolean {
    const vcc = component.terminals["V+"];
    const gnd = component.terminals.GND;

    if (!vcc || !gnd) {
      return false;
    }

    const vccVoltage = this.powerState.netVoltages[vcc];
    const gndVoltage = this.powerState.netVoltages[gnd];

    if (
      typeof vccVoltage !== "number" ||
      typeof gndVoltage !== "number"
    ) {
      return false;
    }

    /*
     * Prefer the explicit rail topology when available. This prevents a
     * floating/ambiguous net from being treated as a powered servo just
     * because a stale pin voltage exists.
     */
    const hasPositiveSource =
      this.powerState.sourceNets.has(vcc) ||
      vccVoltage >= 3;

    const hasGroundReference =
      this.powerState.groundNets.has(gnd) ||
      Math.abs(gndVoltage) < 0.05;

    return (
      hasPositiveSource &&
      hasGroundReference &&
      vccVoltage - gndVoltage >= 3
    );
  }

